// Package typegen generates collection names, field names, and select values
// from PocketBase's schema without bootstrapping or modifying its database.
package typegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

// Collection contains only schema data needed by Go and TypeScript generators.
// Authentication configuration, provider credentials, and rules are excluded.
type Collection struct {
	ID     string  `json:"id"`
	Name   string  `json:"name"`
	Type   string  `json:"type"`
	System bool    `json:"system"`
	Fields []Field `json:"fields"`
}

type Field struct {
	Name         string   `json:"name"`
	Type         string   `json:"type"`
	Required     bool     `json:"required,omitempty"`
	System       bool     `json:"system,omitempty"`
	Hidden       bool     `json:"hidden,omitempty"`
	MaxSelect    int      `json:"maxSelect,omitempty"`
	Values       []string `json:"values,omitempty"`
	CollectionID string   `json:"collectionId,omitempty"`
	OnCreate     bool     `json:"onCreate,omitempty"`
	OnUpdate     bool     `json:"onUpdate,omitempty"`
}

// DecodeSchema accepts a PocketBase Dashboard JSON export (an array).
func DecodeSchema(data []byte) ([]Collection, error) {
	var schema []Collection
	if err := json.Unmarshal(data, &schema); err != nil {
		return nil, fmt.Errorf("decode collections JSON (expected an array): %w", err)
	}
	if schema == nil {
		return nil, fmt.Errorf("schema must be a JSON array of collections")
	}
	for _, collection := range schema {
		if collection.Fields == nil {
			return nil, fmt.Errorf("collection %q has no fields array; export from PocketBase 0.23 or newer", collection.Name)
		}
	}
	return schema, nil
}

// Normalize returns a deterministic copy, omitting internal system collections.
func Normalize(schema []Collection, includeSystem bool) []Collection {
	result := make([]Collection, 0, len(schema))
	for _, collection := range schema {
		if collection.System && !includeSystem {
			continue
		}
		collection.Fields = append([]Field{}, collection.Fields...)
		for i := range collection.Fields {
			collection.Fields[i].Values = append([]string(nil), collection.Fields[i].Values...)
			sort.Strings(collection.Fields[i].Values)
		}
		sort.Slice(collection.Fields, func(i, j int) bool { return collection.Fields[i].Name < collection.Fields[j].Name })
		result = append(result, collection)
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Name < result[j].Name })
	return result
}

// Generate uses untyped string constants for field names so they can be passed
// directly to core.Record.Set/Get and query methods. Select values get distinct
// named string types; PocketBase still validates values and field types on Save.
func Generate(schema []Collection, packageName string) ([]byte, error) {
	if !token.IsIdentifier(packageName) || token.Lookup(packageName).IsKeyword() || packageName == "_" {
		return nil, fmt.Errorf("invalid Go package name %q", packageName)
	}
	if len(schema) == 0 {
		return nil, fmt.Errorf("no application collections found; create a collection or use --include-system")
	}
	schema = Normalize(schema, true)
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by the PocketBase types command. DO NOT EDIT.")
	fmt.Fprintln(&source, "// Regenerate after schema changes with: make types")
	fmt.Fprintf(&source, "\npackage %s\n", packageName)
	identifiers := map[string]string{}
	claim := func(name, origin string) error {
		if previous, exists := identifiers[name]; exists {
			return fmt.Errorf("Go identifier %s collides between %s and %s; rename the schema item", name, previous, origin)
		}
		identifiers[name] = origin
		return nil
	}
	for _, collection := range schema {
		collectionName, err := exportedIdentifier(collection.Name)
		if err != nil {
			return nil, fmt.Errorf("collection %q: %w", collection.Name, err)
		}
		if err := claim(collectionName, fmt.Sprintf("collection %q", collection.Name)); err != nil {
			return nil, err
		}
		fmt.Fprintf(&source, "\n// %s is the %s collection.\nconst %s = %s\n", collectionName, collection.Name, collectionName, strconv.Quote(collection.Name))
		fmt.Fprintln(&source, "\nconst (")
		for _, field := range collection.Fields {
			fieldName, err := exportedIdentifier(field.Name)
			if err != nil {
				return nil, fmt.Errorf("field %s.%s: %w", collection.Name, field.Name, err)
			}
			name := collectionName + "Field" + fieldName
			if err := claim(name, fmt.Sprintf("field %s.%s", collection.Name, field.Name)); err != nil {
				return nil, err
			}
			fmt.Fprintf(&source, "\t%s = %s\n", name, strconv.Quote(field.Name))
		}
		fmt.Fprintln(&source, ")")
		for _, field := range collection.Fields {
			if field.Type != "select" {
				continue
			}
			fieldName, _ := exportedIdentifier(field.Name)
			enumName := collectionName + fieldName
			if err := claim(enumName, fmt.Sprintf("select type %s.%s", collection.Name, field.Name)); err != nil {
				return nil, err
			}
			fmt.Fprintf(&source, "\n// %s lists allowed values for %s.%s.\ntype %s string\n\nconst (\n", enumName, collection.Name, field.Name, enumName)
			for _, value := range field.Values {
				valueName, err := exportedIdentifier(value)
				if err != nil {
					return nil, fmt.Errorf("select value %s.%s %q: %w", collection.Name, field.Name, value, err)
				}
				name := enumName + valueName
				if err := claim(name, fmt.Sprintf("select value %s.%s %q", collection.Name, field.Name, value)); err != nil {
					return nil, err
				}
				fmt.Fprintf(&source, "\t%s %s = %s\n", name, enumName, strconv.Quote(value))
			}
			fmt.Fprintln(&source, ")")
		}
	}
	result, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go source: %w", err)
	}
	return result, nil
}

func exportedIdentifier(value string) (string, error) {
	runes := []rune(value)
	var words []string
	var word []rune
	flush := func() {
		if len(word) > 0 {
			words = append(words, string(word))
			word = nil
		}
	}
	for i, r := range runes {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			flush()
			continue
		}
		if len(word) > 0 && unicode.IsUpper(r) {
			previousLower := unicode.IsLower(runes[i-1]) || unicode.IsDigit(runes[i-1])
			nextLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])
			if previousLower || nextLower {
				flush()
			}
		}
		word = append(word, r)
	}
	flush()
	if len(words) == 0 {
		return "", fmt.Errorf("cannot derive an identifier from %q; use at least one letter or number", value)
	}
	var result strings.Builder
	for _, part := range words {
		switch strings.ToUpper(part) {
		case "ID", "URL", "API", "HTTP", "HTTPS", "UUID", "JSON", "IP":
			result.WriteString(strings.ToUpper(part))
		default:
			runes := []rune(strings.ToLower(part))
			runes[0] = unicode.ToUpper(runes[0])
			result.WriteString(string(runes))
		}
	}
	name := result.String()
	if unicode.IsDigit([]rune(name)[0]) {
		name = "N" + name
	}
	if !token.IsIdentifier(name) {
		return "", fmt.Errorf("%q is not a valid Go identifier", name)
	}
	return name, nil
}
